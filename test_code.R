# To begin with, we set up the values of the true parameters used to generate the data

ar1_cor <- function(n, rho){

  exponent <- abs(matrix(1:n - 1, nrow = n, ncol = n, byrow = TRUE) - (1:n - 1))

  return(rho^exponent)

}

p <- 3   # number of rows of the location, skewness and row covariance matrices

q <- 4   # number of columns of the location, skewness and column covariance matrices

# Definition the true location matrix

M <-  matrix(data = c(1, 2, 1, 2,
                      2, 2, 1, 1,
                      3, 3, 2, 3), p, q, byrow = TRUE)

# Definition of the true skewness matrix

A <-  matrix(data = c(-1,-2,-1,-2,
                      2,-2, 1,-1,
                      3,-3, 2,-3), p, q, byrow = TRUE)

# Definition of the true row covariance matrix

U  <- ar1_cor(p, rho = 0.4) * 1.5

# Definition of the true column covariance matrix (whose determinant equals one to avoid identifiability issues)

V <- ar1_cor (q, rho = 0.8)

V <- V / det(V)^(1 / q)

# We redefine the Frobenius norm here for completeness sake

Frobenius_Norm <- function(A) {

  sqrt(sum(A^2))

  return(sqrt(sum(A^2)))

}

